#!/usr/bin/env python3
"""Build Part 0B: Source Pack (38 documents) coverage report, from final/coverage/*_coverage.csv.

Each reviewer group produced a coverage CSV with columns:
doc, section, aspect_id, aspect_summary, status, blueprint_location, action, new_ids
Usage: python3 blueprint/assembly/build_coverage_report.py
"""
import csv, re, collections
from pathlib import Path

BP = Path(__file__).resolve().parent.parent
COV = BP / "final" / "coverage"
SRC = Path("/tmp/claude-0/-home-user-Allinonecalculator/233b6551-af93-57f5-8f0b-015057ecee11/scratchpad/docs38")
OUT = BP / "Part-00B_Source_Pack_Coverage_Report.md"

GROUPS = {
    "A": ("Business domains", "Part 2.6", ["03", "11", "12", "13", "14", "37"]),
    "B": ("Architecture and workflow", "Part 3.4", ["04", "05", "09", "10"]),
    "C": ("UI catalogue and UX", "Part 2.7a/b", ["06", "17"]),
    "D": ("REST API and integration catalogue", "Part 3.5a/b", ["07"]),
    "E": ("Data catalogue, migration, governance, DR", "Part 3.6a/b", ["08", "28"]),
    "F": ("AI, prompts, RAG, plugins and cost", "Part 7.4a/b", ["15", "16", "21"]),
    "G": ("Unit/SIT/UAT test specifications", "Part 6.8a/b/c", ["19", "22"]),
    "H": ("QC checklist, RTM and backlog", "Part 6.9a/b", ["20", "23", "24"]),
    "I": ("Security, coding, DevOps, environments, performance, pen test, monitoring, release", "Part 4.4a/b", ["18", "25", "26", "27", "29", "30", "31", "32"]),
    "J": ("Training, SaaS service, maintenance, optimization, all numbers", "Part 8.3", ["33", "34", "35", "36", "38"]),
}
STATUSES = ["Covered", "Partially covered", "Not covered", "Conflict", "Not applicable", "Common core"]


def norm_status(s):
    s = (s or "").strip().lower()
    if s.startswith("cover"): return "Covered"
    if s.startswith("partial"): return "Partially covered"
    if s.startswith("not cov"): return "Not covered"
    if s.startswith("conflict"): return "Conflict"
    if s.startswith("not app") or s == "n/a": return "Not applicable"
    if "common" in s: return "Common core"
    return "Other"


def doc_nums(d):
    if "common core" in (d or "").lower() or (d or "").strip().upper().startswith("ALL"):
        return ["ALL"]
    return re.findall(r"(?<!\d)(\d{2})(?!\d)", d or "") or ["ALL"]


titles = {}
sizes = {}
for p in sorted(SRC.glob("*.txt")):
    m = re.match(r"(\d{2})_(.+)\.txt", p.name)
    if m:
        titles[m.group(1)] = m.group(2).replace("_", " ")
        sizes[m.group(1)] = p.stat().st_size

rows = []
for g in GROUPS:
    f = COV / f"{g}_coverage.csv"
    if not f.exists():
        continue
    for r in csv.DictReader(f.open(encoding="utf-8")):
        r["group"] = g
        r["nstatus"] = norm_status(r.get("status"))
        rows.append(r)

per_doc = collections.defaultdict(collections.Counter)
resolved = collections.Counter()
residual = []
for r in rows:
    docs = doc_nums(r.get("doc"))
    st = r["nstatus"]
    for d in docs:
        per_doc[d][st] += 1 / len(docs)
    if st in ("Partially covered", "Not covered", "Conflict"):
        act = (r.get("action") or "") + " " + (r.get("new_ids") or "")
        if act.strip():
            for d in docs:
                resolved[d] += 1 / len(docs)
        else:
            residual.append(r)

tot = collections.Counter()
for r in rows:
    tot[r["nstatus"]] += 1
n_gap = tot["Partially covered"] + tot["Not covered"] + tot["Conflict"]
n_res = n_gap - len(residual)

L = []
A = L.append
A("# AI Growth Engine: Employee Sales & Marketing Automation")
A("## Application Blueprint: PART 0B, Source Pack (38 Documents) Coverage Report")
A("")
A("| Field | Value |\n|---|---|\n| Document | Part 0B (generated by `assembly/build_coverage_report.py` from the reviewer coverage registers in `final/coverage/`) |\n| Version | 1.0 · 27 Nov 2026 |\n| Scope | Line-by-line review of the complete 38-document engineering package against the blueprint, and the enhancements made |\n| Roles applied | All ten expert roles, organized as ten reviewer groups (A–J) |")
A("")
A("## 0B.1 What the source pack is and what it is telling us\n")
A("The 38 documents form one engineering package for the AI Growth Engine. Documents 01 (Business Requirements) and 02 (Functional Specification) are byte-identical to the documents the blueprint was originally built from. Documents 03–36 are domain views of the same product. Each repeats a **common core**: purpose and boundary, Website/Admin operating contract, implementation acceptance controls, optimization engineering and current multi-startup scope. Each then adds its domain specifics: personas, architecture, workflows, UI/API/table catalogues, market and sales playbooks, AI engineering, plugin and cost decisions, security, testing, QC, traceability, DevOps, operations, training, SaaS service and optimization. Document 37 is a worked end-to-end example; document 38 is the authoritative inventory of counts and targets.\n")
A("**Pattern and intent** (the expert reading):\n")
A("1. **Fail-closed, evidence-based delivery.** Every capability is specified with its acceptance evidence. Nothing is \"done\" without a recorded, independently reviewed result, and synthetic or offline checks never count as production certification.")
A("2. **Strict isolation.** The isolation is between Website and Admin, owned portfolio and external clients, and tenants and startups. Shared identity is never shared access.")
A("3. **Configuration, not code.** New startups and clients are onboarded through templates, capability profiles and governed configuration revisions, while running work stays pinned to its revision.")
A("4. **Controlled autonomy.** AI prepares and recommends. Deterministic policy, budget and human approval decide anything consequential. Duplicate and uncertain outcomes are reconciled, never blindly retried.")
A("5. **Open-source first, paid by exception.** Every paid plugin or provider is benchmarked, budgeted and approved, and developer tools are never runtime dependencies.")
A("6. **Measured outcomes.** 35 optimization KPIs (21 mandatory), 104 optimization controls and 24 scenarios measure security, cost, automation, reliability and conversion. They are referred to as **OKPI-01…35** in this blueprint to avoid clashing with business KPIs.")
A("")
A("## 0B.2 How the review was done\n")
A("| Group | Domain | Documents | Enhancement part |\n|---|---|---|---|")
for g, (dom, part, docs) in GROUPS.items():
    A(f"| {g} | {dom} | {', '.join(docs)} | {part} |")
A("| — | Baseline (BRD, FRD) | 01, 02 | Parts 0–9 (original blueprint; identical documents) |")
A("")
A("Each group read its documents completely. Large catalogues (UI 06, API 07, tables 08, plugins 16, tests 22, RTM 24) were also parsed row by row with scripts kept in `assembly/source_pack/`. Every distinct aspect was recorded with a status, its blueprint location and the action taken. The common-core sections are counted once.\n")
A("## 0B.3 Overall result\n")
A("| Status at review time | Aspects |\n|---|---|")
for s in STATUSES:
    if tot[s]:
        A(f"| {s} | {tot[s]:,} |")
A(f"| **Total aspects reviewed** | **{sum(tot.values()):,}** |")
A("")
A(f"**Gaps and conflicts found:** {n_gap:,}. **Addressed by enhancements** (new or refined requirements, designs, catalogue rows, tests, procedures, or a conflict raised for decision): **{n_res:,}**. **Residual items without a recorded action:** {len(residual)} (listed in §0B.6).\n")
A("After the enhancements (Parts 2.6, 2.7, 3.4, 3.5, 3.6, 4.4, 6.8, 6.9, 7.4 and 8.3) and the consolidated decisions (Part 9.1 §9.1.6), every aspect of the 38 documents is either **covered by the blueprint**, **added by an enhancement**, **resolved by a decision**, or explicitly **not applicable** with a reason.\n")
A("## 0B.4 Coverage by document\n")
A("| Doc | Title | Size (KB) | Covered | Partial | Not covered | Conflict | N/A | Gaps addressed | Where |\n|---|---|---|---|---|---|---|---|---|---|")
docmap = {d: g for g, (_, _, ds) in GROUPS.items() for d in ds}
for d in sorted(titles):
    c = per_doc.get(d, collections.Counter())
    if d in ("01", "02"):
        A(f"| {d} | {titles[d]} | {sizes[d]//1024} | Full (baseline) | — | — | — | — | — | Parts 0–9 |")
        continue
    g = docmap.get(d, "?")
    gaps = c["Partially covered"] + c["Not covered"] + c["Conflict"]
    A(f"| {d} | {titles[d]} | {sizes.get(d,0)//1024} | {c['Covered']:.0f} | {c['Partially covered']:.0f} | {c['Not covered']:.0f} | {c['Conflict']:.0f} | {c['Not applicable']:.0f} | {resolved.get(d,0):.0f} / {gaps:.0f} | {GROUPS[g][1] if g in GROUPS else '—'} |")
if per_doc.get("ALL"):
    c = per_doc["ALL"]
    A(f"| All | Common core (shared by all documents) | — | {c['Covered']:.0f} | {c['Partially covered']:.0f} | {c['Not covered']:.0f} | {c['Conflict']:.0f} | {c['Not applicable']:.0f} | — | Parts 0–9 |")
A("\nFractional attributions (aspects shared by several documents) are rounded.\n")
A("## 0B.5 Coverage by reviewer group\n")
A("| Group | Aspects | Covered | Partial | Not covered | Conflict | N/A |\n|---|---|---|---|---|---|---|")
for g in GROUPS:
    c = collections.Counter(r["nstatus"] for r in rows if r["group"] == g)
    if c:
        A(f"| {g} | {sum(c.values()):,} | {c['Covered']:,} | {c['Partially covered']:,} | {c['Not covered']:,} | {c['Conflict']:,} | {c['Not applicable']:,} |")
A("")
A("## 0B.6 Residual items without a recorded action\n")
if residual:
    A("| Group | Doc | Section | Aspect | Status |\n|---|---|---|---|---|")
    for r in residual[:400]:
        A(f"| {r['group']} | {r.get('doc','')} | {(r.get('section') or '')[:60]} | {(r.get('aspect_summary') or '').replace('|','/')[:160]} | {r['nstatus']} |")
else:
    A("None. Every partial, not-covered and conflict aspect has a recorded action.")
A("")
# ---- literal alignment overlay (Part 9.6a/b)
align = {}
for f in sorted(COV.glob("alignment_*.csv")):
    for r in csv.DictReader(f.open(encoding="utf-8")):
        align[(r.get("group", "").strip(), r.get("aspect_id", "").strip())] = r
if align:
    final = collections.Counter()
    types = collections.Counter()
    for r in rows:
        a = align.get((r["group"], (r.get("aspect_id") or "").strip()))
        st = r["nstatus"]
        if a:
            ns_ = (a.get("new_status") or "").lower()
            types[(a.get("alignment_type") or "").strip()[:1].lower() or "?"] += 1
            st = "Not applicable" if ns_.startswith("not app") else ("Cannot match" if ns_.startswith("cannot") else ("Founder-approved deviation" if ns_.startswith("deviation") else "Matched"))
        elif st in ("Covered", "Common core", "Partially covered", "Not covered"):
            st = "Matched"
        final[st] += 1
    appl = sum(final.values()) - final["Not applicable"]
    A("## 0B.7 Final position after enhancement and literal alignment (Part 9.6a/b)\n")
    A("Partially covered and not-covered aspects were completed by the enhancement parts. The 141 conflict aspects were then aligned to the literal source text by the amendment decisions in Part 9.6a (DEC-234…299) and Part 9.6b (DEC-300…379), and every not-applicable reason was re-checked. On 28 Nov 2026 the Founder kept Claude Sonnet as the primary model (DEC-418), which supersedes DEC-301; the two aspects DEC-301 aligned (F15-052, F21-015) are recorded as Founder-approved deviations. The Founder also approved the Vercel + Supabase + AWS Mumbai hosting stack (DEC-421), which makes the deployment-contract aspect B-TC-08 a third Founder-approved deviation.\n")
    A("| Final status | Aspects |\n|---|---|")
    for k in ("Matched", "Founder-approved deviation", "Cannot match", "Not applicable"):
        A(f"| {k} | {final[k]:,} |")
    A(f"| **Applicable aspects** | **{appl:,}** |")
    A(f"| **Literal match** | **{final['Matched'] / appl * 100:.2f}%** ({final['Matched']:,} / {appl:,}) |")
    if final["Founder-approved deviation"]:
        A(f"| Match including Founder-approved deviations | {(final['Matched'] + final['Founder-approved deviation']) / appl * 100:.0f}% of applicable aspects have a recorded, approved disposition |")
    A("")
    lab = {"a": "(a) Source adopted literally", "b": "(b) Both satisfied (source met, stricter control kept)",
           "c": "(c) Source internally inconsistent: all statements satisfied, or pack precedence applied", "d": "(d) Cannot match literally"}
    A("| Alignment type (conflict and re-checked rows) | Rows |\n|---|---|")
    for k, v in sorted(types.items()):
        A(f"| {lab.get(k, k)} | {v} |")
    A("")
    print("ALIGNED", dict(final), f"{final['Matched'] / appl * 100:.2f}%", dict(types))

A("## 0B.8 Detailed registers\n")
A("The full aspect-level registers (one row per aspect, with blueprint location and action) are in `final/coverage/<group>_coverage.csv` and in the detailed register sections of each enhancement part. Catalogue mappings:")
A("- `D_api_mapping.csv`: 321 source API/adapter operations → blueprint API IDs.")
A("- `E_table_mapping.csv`: 155 source tables → blueprint entities.")
A("- `F_integration_candidates.csv`: 538 integration candidates with decisions.")
A("- `G_test_mapping.csv`: 799 source tests → blueprint test cases.")
A("- `H_*_map.csv`: BRs, FRs, QCs, decisions, work items, SIT aliases and runbooks.")
A("- `alignment_a.csv`, `alignment_b.csv`: literal alignment of every conflict aspect (Part 9.6a/b).")
A("")
A("**Status: Part 0B complete.**")
OUT.write_text("\n".join(L) + "\n", encoding="utf-8")
print(OUT, "rows", len(rows), dict(tot), "residual", len(residual))
