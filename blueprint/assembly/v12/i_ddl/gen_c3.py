"""Group I (Part 11.9) generator for DDL-V12-I Appendix C3 part 3 (grants, RLS, indexes, registry triggers).
Reads the live catalogue of a scratch PostgreSQL 16 database that already has Appendix C, C2 and C3 parts 1-2 applied.
Usage: python3 -I gen_c3.py <psql-conn-args...>  -> writes c3_part3_generated.sql"""
import subprocess, sys, os
CONN = sys.argv[1:]
def q(sql):
    out = subprocess.run(['psql', *CONN, '-At', '-F', '|', '-c', sql], capture_output=True, text=True, check=True).stdout
    return [l.split('|') for l in out.strip().split('\n') if l]
tables = [r[0] for r in q("select c.relname from pg_class c where c.relnamespace='public'::regnamespace and c.relkind='r' order by c.oid")]
cols = {}
for t, c, n in q("select table_name, column_name, is_nullable from information_schema.columns where table_schema='public'"):
    cols.setdefault(t, {})[c] = (n == 'YES')
domain = [t for t in tables if 'schema_ref' in cols[t] and 'evidence_refs' in cols[t]]
GLOBAL = ['ai_model','prompt_version','eval_suite','eval_run','fx_rate','jurisdiction_pack','jurisdiction_rule','locale_bundle','sod_conflict',
          'tax_rule','ops_incident','incident_notification','security_finding','domain_schema_registry','metric_definition','sli_sample']
APPEND_ONLY = ['audit_event','consent_record','ai_usage_event','business_event','domain_record_version']
SECRET = ['api_key','scim_token','tenant_data_key','identity_provider','tenant_key_config']
SPECIAL = ['tenant','inbox','incident','portfolio_grant','journey_event','audit_event']
out = ["-- C3-13 (generated by gen_c3.py) Grants, RLS policies, indexes and domain-registry triggers"]
out.append("ALTER TABLE inbox ALTER COLUMN tenant_id SET NOT NULL;")
# ---- grants
for t in tables:
    if t in GLOBAL:
        role = 'ge_platform_sec' if t in ('security_finding',) else 'ge_app, ge_worker, ge_readonly'
        out.append(f"GRANT SELECT ON {t} TO {role};")
        if t in ('security_finding','incident_notification','ops_incident'):
            out.append(f"GRANT SELECT, INSERT, UPDATE ON {t} TO ge_platform_sec;")
        continue
    if t == 'audit_event':
        out.append("GRANT SELECT ON audit_event TO ge_app, ge_worker, ge_readonly;  -- INSERT only through fn_append_audit()")
        continue
    if t in APPEND_ONLY:
        out.append(f"GRANT SELECT, INSERT ON {t} TO ge_app, ge_worker;")
    else:
        out.append(f"GRANT SELECT, INSERT, UPDATE ON {t} TO ge_app, ge_worker;")
    if t not in SECRET:
        out.append(f"GRANT SELECT ON {t} TO ge_readonly;")
out.append("GRANT USAGE ON ALL SEQUENCES IN SCHEMA public TO ge_app, ge_worker;")
# ---- RLS: drop V12 FOR ALL tenant policies, create command-split policies
existing = q("select tablename, policyname from pg_policies where schemaname='public'")
for t, p in existing:
    out.append(f"DROP POLICY IF EXISTS {p} ON {t};")
T = "tenant_id = (SELECT app_tenant())"
C = "company_id = ANY ((SELECT app_company_ids())::uuid[])"
W = "company_id = (SELECT app_write_company())"
pol_register = []
for t in tables:
    if t in GLOBAL:
        continue
    c = cols[t]
    out.append(f"ALTER TABLE {t} ENABLE ROW LEVEL SECURITY; ALTER TABLE {t} FORCE ROW LEVEL SECURITY;")
    if t == 'tenant':
        out.append(f"CREATE POLICY rls_tenant__select ON tenant FOR SELECT USING ({T});")
        pol_register.append((t, 'P-TEN-SELF', 'select'))
        continue
    if t == 'portfolio_grant':
        out.append(f"CREATE POLICY rls_portfolio_grant__select ON portfolio_grant FOR SELECT USING ({T} AND ({C} OR portfolio_id = (SELECT app_portfolio_id())) AND revoked_at IS NULL AND expires_at > now());")
        out.append(f"CREATE POLICY rls_portfolio_grant__insert ON portfolio_grant FOR INSERT WITH CHECK ({T} AND {W} AND (SELECT app_actor_kind()) = 'internal');")
        out.append(f"CREATE POLICY rls_portfolio_grant__update ON portfolio_grant FOR UPDATE USING ({T} AND {W}) WITH CHECK ({T} AND {W});")
        pol_register.append((t, 'P-PORTFOLIO', 'select/insert/update'))
        continue
    if t == 'incident':
        out.append(f"CREATE POLICY rls_incident__select ON incident FOR SELECT TO ge_app, ge_worker, ge_readonly USING ({T});")
        out.append(f"CREATE POLICY rls_incident__insert ON incident FOR INSERT TO ge_app, ge_worker WITH CHECK ({T});")
        out.append("CREATE POLICY rls_incident__platform ON incident FOR ALL TO ge_platform_sec USING (true) WITH CHECK (true);")
        out.append("GRANT SELECT, INSERT, UPDATE ON incident TO ge_platform_sec;")
        pol_register.append((t, 'P-TEN + P-PLATFORM', 'select/insert; platform all'))
        continue
    if t == 'journey_event':
        out.append(f"CREATE POLICY rls_journey_event__subscriber ON journey_event FOR SELECT TO ge_app, ge_worker USING (audience = 'subscriber' AND {T});")
        out.append(f"CREATE POLICY rls_journey_event__insert ON journey_event FOR INSERT TO ge_app, ge_worker WITH CHECK ((audience = 'subscriber' AND {T}) OR (audience = 'operator' AND tenant_id IS NULL AND (SELECT app_actor_kind()) = 'service'));")
        out.append("CREATE POLICY rls_journey_event__operator ON journey_event FOR SELECT TO ge_readonly USING (audience = 'operator');")
        pol_register.append((t, 'P-JOURNEY', 'subscriber/operator split'))
        continue
    if t == 'inbox':
        out.append(f"CREATE POLICY rls_inbox__select ON inbox FOR SELECT USING ({T});")
        out.append(f"CREATE POLICY rls_inbox__insert ON inbox FOR INSERT WITH CHECK ({T} AND (SELECT app_actor_kind()) = 'service');")
        out.append(f"CREATE POLICY rls_inbox__update ON inbox FOR UPDATE USING ({T}) WITH CHECK ({T});")
        pol_register.append((t, 'P-TEN (service insert)', 'select/insert/update'))
        continue
    if 'company_id' in c:
        nullable = c['company_id']
        csel = f"({C} OR company_id IS NULL)" if nullable else C
        cw = f"({W} OR (company_id IS NULL AND (SELECT app_actor_kind()) = 'service'))" if nullable else W
        out.append(f"CREATE POLICY rls_{t}__select ON {t} FOR SELECT USING ({T} AND {csel});")
        if t == 'audit_event':
            pol_register.append((t, 'P-CO-NULLABLE (select only; insert via fn_append_audit)', 'select'))
            continue
        out.append(f"CREATE POLICY rls_{t}__insert ON {t} FOR INSERT WITH CHECK ({T} AND {cw});")
        if t not in APPEND_ONLY:
            out.append(f"CREATE POLICY rls_{t}__update ON {t} FOR UPDATE USING ({T} AND {cw}) WITH CHECK ({T} AND {cw});")
        pol_register.append((t, 'P-CO-NULLABLE' if nullable else 'P-CO', 'select/insert' + ('' if t in APPEND_ONLY else '/update')))
    else:
        out.append(f"CREATE POLICY rls_{t}__select ON {t} FOR SELECT USING ({T});")
        out.append(f"CREATE POLICY rls_{t}__insert ON {t} FOR INSERT WITH CHECK ({T});")
        if t not in APPEND_ONLY:
            out.append(f"CREATE POLICY rls_{t}__update ON {t} FOR UPDATE USING ({T}) WITH CHECK ({T});")
        pol_register.append((t, 'P-TEN', 'select/insert' + ('' if t in APPEND_ONLY else '/update')))
# audit writer function runs as definer (owner); allow definer insert path
out.append("CREATE POLICY rls_audit_event__insert_definer ON audit_event FOR INSERT TO CURRENT_USER WITH CHECK (tenant_id = (SELECT app_tenant()));")
# ---- indexes: every FK without a supporting index
fks = q("""select c.conrelid::regclass::text, (select string_agg(a.attname, ',' order by k.ord) from unnest(c.conkey) with ordinality k(attnum, ord)
 join pg_attribute a on a.attrelid=c.conrelid and a.attnum=k.attnum) from pg_constraint c where contype='f' and connamespace='public'::regnamespace
 and not exists (select 1 from pg_index i where i.indrelid=c.conrelid and (i.indkey::int2[])[0:array_length(c.conkey,1)-1] @> c.conkey
 and (i.indkey::int2[])[0:array_length(c.conkey,1)-1] <@ c.conkey)""")
seen = set(); idx = []
for t, colsx in fks:
    key = (t, colsx)
    if key in seen: continue
    seen.add(key)
    name = f"ix_{t}__{colsx.replace(',', '_')}"[:63]
    idx.append((name, t, colsx, 'FK support (IX-R1)'))
for t in domain:
    idx.append((f"ix_{t}__scope_status_upd"[:63], t, "tenant_id, company_id, status, updated_at DESC", 'V5 common physical design'))
    idx.append((f"ix_{t}__schema_ref"[:63], t, "tenant_id, company_id, schema_ref", 'registry lookup'))
for t in ['growth_signal','growth_need','growth_opportunity','growth_need_evidence','growth_claim','growth_evidence','growth_market_event','growth_score_version']:
    if t in tables: idx.append((f"ixg_{t}__evidence_refs", t, "USING gin (evidence_refs)", 'evidence lookup'))
special = [
 ("ixp_outbox__pending","outbox","next_attempt_at, event_id) WHERE (published_at IS NULL","dispatcher claim FOR UPDATE SKIP LOCKED"),
 ("ix_workflow_run__scope_status","workflow_run","tenant_id, company_id, status, created_at DESC","live monitor"),
 ("ixp_workflow_run__active","workflow_run","tenant_id, company_id, created_at) WHERE (status IN ('Queued','Running','Awaiting approval','Held','Reconciling')","queue"),
 ("ixp_effect__open","effect","tenant_id, company_id, status) WHERE (status IN ('Intended','Dispatched','Reconciling')","reconciliation"),
 ("ix_consent_record__current","consent_record","tenant_id, company_id, contact_id, channel, purpose, captured_at DESC","PDP consent lookup"),
 ("ixp_dsar_request__open","dsar_request","tenant_id, due_at) WHERE (status NOT IN ('Completed','Rejected')","DSAR clock"),
 ("ixb_audit_event__time","audit_event","USING brin (occurred_at)","time-range audit search"),
 ("ix_audit_event__object","audit_event","tenant_id, object_type, ref, occurred_at DESC","object history"),
 ("ixb_ai_usage_event__time","ai_usage_event","USING brin (occurred_at)","usage scans"),
 ("ix_ai_usage_event__scope_time","ai_usage_event","tenant_id, company_id, occurred_at","cost per company per day"),
 ("ixp_webhook_delivery__pending","webhook_delivery","tenant_id, endpoint_id, signed_at) WHERE (delivered_at IS NULL","retry worker"),
 ("ixp_api_key__live","api_key","tenant_id) WHERE (revoked_at IS NULL","key listing"),
 ("ixp_security_finding__open","security_finding","severity, due_at) WHERE (closed_at IS NULL","release gate KPI-03"),
 ("ix_export_job__status","export_job","tenant_id, status","export queue"),
 ("ix_business_event__time","business_event","tenant_id, company_id, occurred_at","KPI period scans"),
 ("ixp_business_event__campaign","business_event","tenant_id, company_id, campaign_id, occurred_at) WHERE (campaign_id IS NOT NULL","attribution"),
 ("ix_business_event__wf","business_event","tenant_id, company_id, sku_id, wf_id, occurred_at","service/workflow filter MT-27"),
 ("ixp_incident_notification__due","incident_notification","deadline_at) WHERE (notified_at IS NULL","breach clock A121"),
 ("ixp_inbox__unprocessed","inbox","tenant_id, received_at) WHERE (processed_at IS NULL","inbound processing"),
 ("ixp_portfolio_grant__live","portfolio_grant","tenant_id, portfolio_id) WHERE (revoked_at IS NULL","portfolio scope"),
 ("ix_jurisdiction_pack__status","jurisdiction_pack","jurisdiction, status","PDP pack lookup"),
 ("ix_metric_aggregate__lookup","metric_aggregate","tenant_id, company_id, metric_id, period_start","dashboard"),
]
idx += special
for name, t, colsx, why in idx:
    if colsx.startswith('USING'):
        out.append(f"CREATE INDEX IF NOT EXISTS {name} ON {t} {colsx};  -- {why}")
    else:
        out.append(f"CREATE INDEX IF NOT EXISTS {name} ON {t} ({colsx});  -- {why}")
# ---- domain registry triggers
for t in domain:
    out.append(f"CREATE TRIGGER trg_{t}_validate BEFORE INSERT OR UPDATE ON {t} FOR EACH ROW EXECUTE FUNCTION fn_validate_domain_row();")
open('c3_part3_generated.sql', 'w').write('\n'.join(out) + '\n')
with open('c3_policy_register.csv', 'w') as f:
    f.write('table,template,commands\n')
    for r in pol_register: f.write(','.join(f'"{x}"' for x in r) + '\n')
with open('c3_index_register.csv', 'w') as f:
    f.write('index,table,definition,purpose\n')
    for r in idx: f.write(','.join('"' + x.replace('"', '""') + '"' for x in r) + '\n')
print(len(tables), 'tables;', len(domain), 'domain;', len(pol_register), 'policy-tables;', len(idx), 'indexes')
